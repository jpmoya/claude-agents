# #632 AC10–AC14 — the prose side of "claude-agents is direct-route", pinned by literal strings in tracked files
# (same style as test-adjudicator-files-fix.sh). Prefix drd_.
#   AC10 pipeline-adjudicator.md never queues (no `--add-label agent-go`), still files, says the session implements it
#   AC11 product-manager.md never adds agent-go on a direct-route repo
#   AC12 CLAUDE.md carries the rule sentence verbatim and no longer the "may edit directly" / "files and queues" wording
#   AC13 delivery-lead.md and the lead's brief carry the report heading; the lead never dispatches direct-route tickets
#        (the brief is composed by goal_brief in goal-lib.sh — deliver.sh holds no brief text — so that is the file pinned;
#        test-goal-z-direct-route.sh checks the generated brief itself)
#   AC14 blocked-chain-stop.sh guidance text (SCOPE_RE untouched) and README

ROOT_DRD=$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)
ADJ_DRD="$ROOT_DRD/agents/pipeline-adjudicator.md"
PM_DRD="$ROOT_DRD/agents/product-manager.md"
LEAD_DRD="$ROOT_DRD/agents/delivery-lead.md"
CMD_DRD="$ROOT_DRD/CLAUDE.md"
HOOK_DRD="$ROOT_DRD/hooks/blocked-chain-stop.sh"
README_DRD="$ROOT_DRD/README.md"
GOALLIB_DRD="$ROOT_DRD/skills/orchestrate/goal-lib.sh"

drd_has() { grep -qF -- "$2" "$1" || { fail "$(basename "$1"): missing [$2]"; return 1; }; }
drd_lacks() { if grep -qF -- "$2" "$1"; then fail "$(basename "$1"): still contains [$2]"; return 1; fi; }

test_drd_ac10_adjudicator_files_but_never_queues() {
  drd_lacks "$ADJ_DRD" '--add-label agent-go' || return 1
  drd_has "$ADJ_DRD" 'gh issue create --repo jpmoya/claude-agents' || return 1
  drd_has "$ADJ_DRD" '--add-label user-feedback' || return 1
  drd_has "$ADJ_DRD" 'implements it directly' || return 1
  drd_has "$ADJ_DRD" 'direct route' || return 1
  drd_has "$ADJ_DRD" 'filed #<n> — the session that ran this review implements it directly now (direct route, see CLAUDE.md)' || return 1
  drd_has "$ADJ_DRD" 'JP, 2026-11-09: claude-agents is direct-route' || return 1
  drd_lacks "$ADJ_DRD" 'every self-healing ticket the adjudicator files must be auto-dispatched' || return 1
  local d; d=$(grep '^description:' "$ADJ_DRD")
  assert_not_contains "$d" 'queues it with agent-go' "AC10: frontmatter description" || return 1
  assert_contains "$d" 'for the interactive session to implement directly' "AC10: frontmatter description" || return 1
}

test_drd_ac11_pm_never_adds_agent_go_on_a_direct_route_repo() {
  drd_has "$PM_DRD" 'Never for a direct-route repo' || return 1
  drd_has "$PM_DRD" 'DIRECT_ROUTE_REPOS' || return 1
  # the exclusion sits in all three inheritance paths: dependency follow-ups, approved-goal children, goal-label inheritance
  assert_eq "$(grep -c 'direct-route' "$PM_DRD")" "3" "AC11: one direct-route exclusion per inheritance section" || return 1
}

test_drd_ac12_claude_md_rule() {
  drd_has "$CMD_DRD" 'Every change to jpmoya/claude-agents — features, fixes, enhancements, pipeline self-heal tickets — is done directly by the interactive session, never through the pipeline.' || return 1
  drd_has "$CMD_DRD" 'orchestrate.sh refuses the repo' || return 1
  drd_has "$CMD_DRD" 'DIRECT_ROUTE_REPOS' || return 1
  drd_has "$CMD_DRD" 'never asks JP to merge' || return 1
  drd_has "$CMD_DRD" 'files its own fix ticket (no `agent-go`)' || return 1
  drd_has "$CMD_DRD" 'on the claude-agents repo the session resolves a blocked ticket directly (it is the implementer) instead of relaunching the orchestrator' || return 1
  drd_lacks "$CMD_DRD" 'is exempt from the pipeline-only rule above. An interactive session may edit it directly' || return 1
  drd_lacks "$CMD_DRD" 'files and queues (`agent-go`) its own fix ticket' || return 1
}

test_drd_ac13_delivery_lead_and_brief() {
  local heading='Direct route — needs the interactive session'
  drd_has "$LEAD_DRD" "$heading" || return 1
  drd_has "$GOALLIB_DRD" "$heading" || return 1
  # the brief is generated by goal_brief: the heading must be inside that function, not a stray comment elsewhere
  awk '/^goal_brief\(\)/ {on=1} on {print} on && /^}/ {exit}' "$GOALLIB_DRD" | grep -qF -- "$heading" \
    || { fail "goal-lib.sh: goal_brief does not emit [$heading]"; return 1; }
  # "never dispatch" in the same paragraph (line) as "direct-route"
  grep -F -- 'direct-route' "$LEAD_DRD" | grep -qF -- 'never dispatch' \
    || { fail "delivery-lead.md: no paragraph says 'never dispatch' about a direct-route ticket"; return 1; }
  drd_has "$LEAD_DRD" 'DIRECT_ROUTE_REPOS' || return 1
  drd_lacks "$LEAD_DRD" 'fix ticket queued' || return 1
  drd_lacks "$LEAD_DRD" 'launch the fix ticket' || return 1
}

test_drd_ac14_hook_text_and_readme() {
  drd_has "$HOOK_DRD" 'direct-route repo' || return 1
  drd_has "$HOOK_DRD" 'do not relaunch' || return 1
  grep '^SCOPE_RE=' "$HOOK_DRD" | grep -q 'claude-agents' || { fail "blocked-chain-stop.sh: SCOPE_RE must still match claude-agents"; return 1; }
  # guidance only: the direct-route words sit in the message text, not in a condition
  grep -nF 'direct-route' "$HOOK_DRD" | grep -qE '^[0-9]+:[0-9]\. Relaunch' || { fail "blocked-chain-stop.sh: direct-route text must be in the 'Relaunch' guidance step"; return 1; }
  bash -n "$HOOK_DRD" || return 1
  drd_has "$README_DRD" 'DIRECT_ROUTE_REPOS' || return 1
  drd_has "$README_DRD" '## Direct-route repos' || return 1
  drd_lacks "$README_DRD" 'labelled `agent-go`, skipped if a ticket for that incident already exists' || return 1
}

echo "-- direct-route repos: docs and agent rules (issue #632 AC10-AC14)"
run_test test_drd_ac10_adjudicator_files_but_never_queues
run_test test_drd_ac11_pm_never_adds_agent_go_on_a_direct_route_repo
run_test test_drd_ac12_claude_md_rule
run_test test_drd_ac13_delivery_lead_and_brief
run_test test_drd_ac14_hook_text_and_readme
